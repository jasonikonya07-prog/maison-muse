import base64
import hashlib
import hmac
import os
import re
from collections.abc import Mapping, Sequence
from functools import lru_cache
from typing import Any

from cryptography.fernet import Fernet, InvalidToken


ENCRYPTED_PREFIX = "enc:v1:"
SENSITIVE_COLUMNS_BY_TABLE = {
    "users": {"phone", "whatsapp_number"},
    "sellers": {
        "business_phone",
        "payout_account",
        "whatsapp_phone",
        "whatsapp_number",
    },
    "seller_profiles": {"business_phone", "payout_number"},
    "seller_branches": {"address", "phone"},
    "seller_profile_update_tokens": {"new_phone"},
    "products": {"seller_phone", "farmer_whatsapp", "seller_whatsapp_phone"},
    "orders": {"customer_phone", "delivery_address", "mpesa_phone"},
    "support_tickets": {"customer_phone"},
}
SENSITIVE_RESULT_COLUMNS = set().union(*SENSITIVE_COLUMNS_BY_TABLE.values()) | {
    "phone",
    "address",
    "linked_seller_phone",
    "linked_seller_whatsapp_phone",
    "linked_farmer_whatsapp_number",
}

_INSERT_PATTERN = re.compile(
    r"\bINSERT\s+(?:OR\s+IGNORE\s+)?INTO\s+"
    r'["`]?([a-zA-Z_]\w*)["`]?\s*\(([^)]*)\)\s*VALUES\s*\(([^)]*)\)',
    re.IGNORECASE | re.DOTALL,
)
_UPDATE_PATTERN = re.compile(
    r'\bUPDATE\s+["`]?([a-zA-Z_]\w*)["`]?\s+SET\s+(.*?)(?:\s+WHERE\b|$)',
    re.IGNORECASE | re.DOTALL,
)
_PLACEHOLDER_PATTERN = re.compile(r"%\([^)]+\)s|%s|\?")


@lru_cache(maxsize=4)
def _fernet_for_key(key: str) -> Fernet:
    try:
        return Fernet(key.encode("ascii"))
    except (UnicodeEncodeError, ValueError) as error:
        raise RuntimeError(
            "DATA_ENCRYPTION_KEY must be a valid Fernet key generated by "
            "cryptography.fernet.Fernet.generate_key()."
        ) from error


def _fernet() -> Fernet:
    key = os.getenv("DATA_ENCRYPTION_KEY", "").strip()
    if not key:
        raise RuntimeError(
            "DATA_ENCRYPTION_KEY is required for PostgreSQL. Generate a Fernet "
            "key and set it as a private backend environment variable."
        )
    return _fernet_for_key(key)


def encrypt_value(value: Any) -> Any:
    if value is None or value == "" or not isinstance(value, str):
        return value
    if value.startswith(ENCRYPTED_PREFIX):
        return value
    encrypted = _fernet().encrypt(value.encode("utf-8")).decode("ascii")
    return ENCRYPTED_PREFIX + encrypted


def decrypt_value(value: Any) -> Any:
    if not isinstance(value, str) or not value.startswith(ENCRYPTED_PREFIX):
        return value
    try:
        encrypted = value.removeprefix(ENCRYPTED_PREFIX).encode("ascii")
        return _fernet().decrypt(encrypted).decode("utf-8")
    except (InvalidToken, UnicodeDecodeError, UnicodeEncodeError) as error:
        raise RuntimeError(
            "Unable to decrypt database data. Confirm DATA_ENCRYPTION_KEY matches "
            "the key used to encrypt this database."
        ) from error


def decrypt_result_value(column: str, value: Any) -> Any:
    if column.casefold() in SENSITIVE_RESULT_COLUMNS:
        return decrypt_value(value)
    return value


def phone_lookup_hash(phone: str) -> str:
    key = os.getenv("DATA_ENCRYPTION_KEY", "").strip()
    _fernet()
    raw_key = base64.urlsafe_b64decode(key.encode("ascii"))
    lookup_key = hashlib.sha256(
        b"maison-muse-phone-index:v1:" + raw_key
    ).digest()
    return hmac.new(lookup_key, phone.encode("utf-8"), hashlib.sha256).hexdigest()


def encrypt_write_parameters(
    query: str, parameters: Sequence[Any] | Mapping[str, Any]
) -> Sequence[Any] | Mapping[str, Any]:
    insert_match = _INSERT_PATTERN.search(query)
    if insert_match:
        table, columns_text, values_text = insert_match.groups()
        sensitive_columns = SENSITIVE_COLUMNS_BY_TABLE.get(table.casefold(), set())
        if not sensitive_columns:
            return parameters
        columns = [column.strip().strip('"`').casefold() for column in columns_text.split(",")]
        expressions = [expression.strip() for expression in values_text.split(",")]
        if isinstance(parameters, Mapping):
            return {
                key: encrypt_value(value)
                if key.casefold() in sensitive_columns
                else value
                for key, value in parameters.items()
            }
        encrypted_parameters = list(parameters)
        parameter_index = 0
        for column, expression in zip(columns, expressions):
            placeholders = list(_PLACEHOLDER_PATTERN.finditer(expression))
            if column in sensitive_columns and expression in {"?", "%s"} and placeholders:
                if parameter_index < len(encrypted_parameters):
                    encrypted_parameters[parameter_index] = encrypt_value(
                        encrypted_parameters[parameter_index]
                    )
            parameter_index += len(placeholders)
        return tuple(encrypted_parameters)

    update_match = _UPDATE_PATTERN.search(query)
    if update_match:
        table, assignments_text = update_match.groups()
        sensitive_columns = SENSITIVE_COLUMNS_BY_TABLE.get(table.casefold(), set())
        if not sensitive_columns:
            return parameters
        assignments = [assignment.strip() for assignment in assignments_text.split(",")]
        if isinstance(parameters, Mapping):
            encrypted_parameters = dict(parameters)
            for assignment in assignments:
                match = re.match(
                    r'["`]?([a-zA-Z_]\w*)["`]?\s*=\s*%\(([a-zA-Z_]\w*)\)s$',
                    assignment,
                )
                if match and match.group(1).casefold() in sensitive_columns:
                    parameter_name = match.group(2)
                    if parameter_name in encrypted_parameters:
                        encrypted_parameters[parameter_name] = encrypt_value(
                            encrypted_parameters[parameter_name]
                        )
            return encrypted_parameters

        encrypted_parameters = list(parameters)
        parameter_index = 0
        for assignment in assignments:
            match = re.match(
                r'["`]?([a-zA-Z_]\w*)["`]?\s*=\s*(.*?)$', assignment, re.DOTALL
            )
            expression = match.group(2).strip() if match else ""
            placeholders = list(_PLACEHOLDER_PATTERN.finditer(expression))
            column = match.group(1).casefold() if match else ""
            if (
                column in sensitive_columns
                and expression in {"?", "%s"}
                and placeholders
                and parameter_index < len(encrypted_parameters)
            ):
                encrypted_parameters[parameter_index] = encrypt_value(
                    encrypted_parameters[parameter_index]
                )
            parameter_index += len(placeholders)
        return tuple(encrypted_parameters)

    return parameters
